'use strict';
const fs = require('fs');
const assert = require('node:assert/strict');
const source = fs.readFileSync('b.js','utf8');
const orig = JSON.parse(fs.readFileSync('sets/b-2025-spring.json','utf8'));
const metadata = JSON.parse(fs.readFileSync('sets/b-meta-2025-spring.json','utf8'));
const index = JSON.parse(fs.readFileSync('sets/b-index.json','utf8'));
assert.equal(index.find(x=>x.id===orig.id)?.metadataFile,'sets/b-meta-2025-spring.json');
assert.equal(metadata.setId,orig.id);
assert.equal(metadata.schemaVersion,'ap-b-field-meta-v1');
assert.equal(orig.questions.length,11);
const hstart=source.indexOf('const META_SCHEMA=');
const hend=source.indexOf('function validateSet(o){',hstart);
const vstart=hend;
const vend=source.indexOf('function getQ(',vstart);
assert(hstart>0&&hend>hstart&&vend>vstart);
const engine = new Function('shortTypes','text',source.slice(hstart,hend)+'\n'+source.slice(vstart,vend)+'\nreturn {applyAnswerMetadata,loadAnswerMetadata,filterAllowed,validateSet};')(
 new Set(['single','multi','dropdown','word','short','long']),v=>String(v??'')
);
const enriched=engine.applyAnswerMetadata(orig,metadata);
assert.equal(enriched.questions.length,11);
const counts=enriched.questions.map(q=>q.fields.length);
assert.equal(enriched.questions[0].fields.length,8);
assert.equal(enriched.questions[3].fields.length,9);
assert.equal(enriched.questions[10].fields.some(f=>f.id==='s3'&&f.fallback),true);
assert.equal(orig.questions[0].fields.length,5,'do not mutate source past exam JSON');
assert.equal(enriched.questions.reduce((n,q)=>n+q.fields.filter(f=>!f.fallback).length,0),94);
const exact=enriched.questions.flatMap(q=>q.fields).filter(f=>f.grading==='exact');
assert.equal(exact.length,30);
assert(exact.every(f=>f.verified&&f.correct?.length&&['single','multi','dropdown','word'].includes(f.type)));
assert.equal(engine.filterAllowed('Aあ1-9B','digits'),'19');
assert.equal(engine.filterAllowed('ab1あ-2','alphanumeric'),'ab12');
const normalized=engine.validateSet(enriched);
assert.equal(normalized.questions[0].fields.length,8);
assert.equal(normalized.questions[10].fields.find(f=>f.id==='s3').grading,'llm');
assert(normalized.questions[10].fields.find(f=>f.id==='s3').fallback);
assert(normalized.questions[0].fields.find(f=>f.id==='s1-1').maxLength===12);
assert(normalized.questions[0].fields.find(f=>f.id==='s1-1').maxLengthVerified);
assert(normalized.questions.every(q=>q.fields.every(f=>f.sourceGroup||f.fallback)));
assert(normalized.questions.some(q=>q.fields.some(f=>f.type==='single')));
assert(normalized.questions.some(q=>q.fields.some(f=>f.type==='word')));
assert(normalized.questions.some(q=>q.fields.some(f=>f.type==='long')));
(async()=>{
  const other=JSON.parse(fs.readFileSync('sets/b-2025-autumn.json','utf8'));
  const fallback=await engine.loadAnswerMetadata(other,{});
  assert(fallback.questions.every(q=>q.fields.every(f=>f.type==='long'&&f.fallback&&f.grading==='llm')));
  const missing={...metadata,questions:{...metadata.questions}};
  delete missing.questions['4'];
  const partial=engine.applyAnswerMetadata(orig,missing);
  assert(partial.questions[3].fields.every(f=>f.fallback));
  console.log('PASS: metadata 2025 spring 94 fields, 30 verified exact, group/whole-set generic fallbacks; 11 questions preserved');
})().catch(e=>{console.error(e);process.exit(1)});
